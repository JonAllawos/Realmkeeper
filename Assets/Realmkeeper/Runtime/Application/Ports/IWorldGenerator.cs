using System;
using Realmkeeper.Domain.Geography;
using Realmkeeper.Domain.Identifiers;
using Realmkeeper.Domain.World;

namespace Realmkeeper.Application.Ports
{
    public sealed class WorldGenerationRequest
    {
        public WorldGenerationRequest(string worldName, long seed, WorldSettings settings, WorldId worldId = default)
        {
            WorldName = worldName;
            Seed = seed;
            Settings = settings;
            WorldId = worldId;
        }

        public string WorldName { get; }
        public long Seed { get; }
        public WorldSettings Settings { get; }

        /// <summary>Optional. When empty a new random world identity is assigned.</summary>
        public WorldId WorldId { get; }

        /// <summary>
        /// False generates the world as schema v6 did: no shops and no starting belongings. Only for building
        /// faithful pre-Phase-5 saves in migration tests; the game always generates with commerce.
        /// </summary>
        public bool IncludeCommerce { get; set; } = true;

        /// <summary>
        /// Phase 10: add the living-world data (the people a settlement's places call for, NPC sheets, settlement layouts,
        /// wildlife). False gives the world as it was before Phase 10, the source of faithful v11 fixtures.
        /// </summary>
        public bool IncludeLivingWorld { get; set; } = true;

        /// <summary>Phase 16: the side the mountains lie on (0–7); null: chosen by the seed. Neighbouring regions continue a range.</summary>
        public int? MountainDirection { get; set; }

        /// <summary>
        /// Phase 16: generate one region of a connected world: its geography, settlements, economy, people, politics,
        /// layouts and wildlife, without the home region's authored quests and places.
        /// </summary>
        public bool RegionOnly { get; set; }
    }

    /// <summary>Generation output: authoritative world data plus the derived geography it sits on.</summary>
    public sealed class GeneratedWorld
    {
        public GeneratedWorld(WorldData world, RegionMap map)
        {
            World = world;
            Map = map;
        }

        public WorldData World { get; }
        public RegionMap Map { get; }
    }

    /// <summary>Thrown by generators when a seed cannot produce a valid world.</summary>
    public sealed class WorldGenerationException : Exception
    {
        public WorldGenerationException(string message) : base(message) { }
    }

    /// <summary>Port implemented by Realmkeeper.Infrastructure.</summary>
    public interface IWorldGenerator
    {
        /// <summary>Version stamped into generated worlds. Bump whenever output for a given seed changes.</summary>
        int GeneratorVersion { get; }

        bool SupportsVersion(int generatorVersion);

        GeneratedWorld Generate(WorldGenerationRequest request);

        /// <summary>Rebuilds the geography of an existing world from its seed and generator version.</summary>
        RegionMap RegenerateRegion(WorldData world);

        /// <summary>
        /// Fills in economy data (production, storage, trade routes) that an older save lacks,
        /// derived from the regenerated geography. Leaves already-initialized settlements alone.
        /// </summary>
        void InitializeEconomy(WorldData world, RegionMap map);

        /// <summary>
        /// Phase 10: fills in the living-world data an older save lacks (people a settlement's places call for, NPC sheets,
        /// settlement identity and layout, wildlife and livestock), derived from the regenerated geography. Never
        /// replaces what exists. True when anything was added.
        /// </summary>
        bool EnsureLivingWorld(WorldData world, RegionMap map);

        /// <summary>Phase 16: rebuilds one region's geography (the home region's or another's, from its own seed and mountain side).</summary>
        RegionMap RegenerateRegion(WorldData world, RegionData region);

        /// <summary>
        /// Phase 16 (ADR-0076): makes the world the connected world its settings ask for, once: the further regions
        /// generated by the same generator and merged, their crossings and the route network. Existing settlements,
        /// people and roads are never regenerated. True when anything was added.
        /// </summary>
        bool EnsureAtlas(WorldData world, RegionMap homeMap, int regions);
    }
}
